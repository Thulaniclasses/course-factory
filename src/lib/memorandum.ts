import type { GeneratedCourse } from "./ai";

/**
 * Generates a comprehensive training memorandum as a plain-text document.
 * This is the "docx conversion source" — buildMemorandumDocx() reads this
 * same structure to produce the actual .docx file.
 */

export interface MemorandumSection {
  heading: string;
  body: string[];
}

export function buildMemorandum(course: GeneratedCourse): MemorandumSection[] {
  const sections: MemorandumSection[] = [];

  // ---- 1. Overview ----
  sections.push({
    heading: "1. Course Overview",
    body: [
      `Title: ${course.title}`,
      `Description: ${course.description}`,
      `Target Audience: ${course.targetAudience || "FIU analysts, compliance officers, and AML/CFT practitioners"}`,
      `Estimated Duration: ${course.estimatedDuration || "Not specified"}`,
      `Total Modules: ${course.modules.length}`,
      `Total Content Cards: ${course.modules.reduce((n, m) => n + m.content.length, 0)}`,
      `Total Assessment Questions: ${course.modules.reduce((n, m) => n + m.quiz.length, 0)}`,
      `Generated: ${new Date(course.generatedAt || Date.now()).toLocaleString()}`,
    ],
  });

  // ---- 2. Learning Objectives (aggregated) ----
  const allObjectives = course.modules.flatMap((m, i) =>
    (m.learningObjectives || []).map((obj) => `Module ${i + 1}: ${obj}`)
  );
  sections.push({
    heading: "2. Learning Objectives",
    body:
      allObjectives.length > 0
        ? allObjectives
        : ["No learning objectives were explicitly generated for this course."],
  });

  // ---- 3. Module-by-Module Summary ----
  const moduleSummaries: string[] = [];
  course.modules.forEach((m, i) => {
    moduleSummaries.push(`MODULE ${i + 1}: ${m.title}`);
    moduleSummaries.push(
      `Content: ${m.content.length} cards covering: ${m.content
        .map((c) => c.slice(0, 80) + (c.length > 80 ? "..." : ""))
        .join(" | ")}`
    );
    moduleSummaries.push(
      `Scenario: ${m.scenario.prompt.slice(0, 150)}${m.scenario.prompt.length > 150 ? "..." : ""}`
    );
    moduleSummaries.push(`Quiz: ${m.quiz.length} question(s)`);
    moduleSummaries.push("");
  });
  sections.push({
    heading: "3. Module-by-Module Summary",
    body: moduleSummaries,
  });

  // ---- 4. Assessment Strategy ----
  const totalQuiz = course.modules.reduce((n, m) => n + m.quiz.length, 0);
  const totalScenarios = course.modules.length;
  sections.push({
    heading: "4. Assessment Strategy",
    body: [
      `Assessment Approach: Blended — interactive scenarios + multiple-choice knowledge checks`,
      `Total Scenarios: ${totalScenarios} (one per module)`,
      `Total Quiz Questions: ${totalQuiz}`,
      `Pass Threshold: 70% (SCORM mastery score)`,
      `Recommendation: Learners should complete all modules sequentially. Quiz answers are tracked via the SCORM runtime; completion is reported to the host LMS.`,
      `Feedback: Each scenario includes detailed feedback for both correct and incorrect choices. Quiz questions include the correct answer index for automated scoring.`,
    ],
  });

  // ---- 5. Delivery Recommendations ----
  sections.push({
    heading: "5. Delivery Recommendations",
    body: [
      `Format: SCORM 1.2 package (LMS-ready)`,
      `Recommended LMS: Any SCORM 1.2-compliant system (Moodle, Cornerstone, Docebo, TalentLMS, SAP SuccessFactors, etc.)`,
      `Delivery Mode: Self-paced e-learning`,
      `Suggested Cadence: Complete in 1-2 sessions (30-60 min total)`,
      `Prerequisites: None`,
      `Accessibility: Keyboard navigation supported; ARIA labels included in the learner player.`,
    ],
  });

  // ---- 6. References ----
  sections.push({
    heading: "6. References and Standards",
    body: [
      `- FATF Recommendations (Financial Action Task Force)`,
      `- Egmont Group Principles for Information Exchange`,
      `- ECOFEL Certification Program (ECP) Standards`,
      `- National Risk Assessment (NRA) Methodology`,
      `- Risk-Based Approach (RBA) Framework`,
      `Note: All terminology and standards references are drawn from internationally recognized AML/CFT frameworks.`,
    ],
  });

  // ---- 7. Footer ----
  sections.push({
    heading: "7. Document Information",
    body: [
      `Generated by: Course Factory AI`,
      `Document Version: 1.0`,
      `For: ${course.targetAudience || "Internal training"}`,
      `This memorandum is auto-generated from course content and is intended for internal training documentation purposes.`,
    ],
  });

  return sections;
}
